import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import assert from "node:assert/strict";
import { once } from "node:events";

const dir=mkdtempSync(join(tmpdir(),"nexus-smoke-"));
process.env.SQLITE_PATH=join(dir,"test.sqlite");
process.env.CORS_ORIGINS="http://localhost";
process.env.ROUTER_CREDENTIAL_KEY="33".repeat(32);
const {default:app}=await import("../src/app.js");
const {db}=await import("../src/config/database.js");
const server=app.listen(0);
await once(server,"listening");
const address=server.address();
const base="http://127.0.0.1:"+address.port;
const request=async(path,method="GET",body,token)=>{
 const headers={"Content-Type":"application/json"};
 if(token)headers.Authorization="Bearer "+token;
 const response=await fetch(base+path,{method,headers,body:body?JSON.stringify(body):undefined});
 const data=await response.json();
 return {status:response.status,data};
};
try{
 db.exec("CREATE TRIGGER fail_setup_session BEFORE INSERT ON sessions BEGIN SELECT RAISE(ABORT, 'injected setup failure'); END");
 const failedSetup=await request("/api/v1/setup","POST",{companyName:"Rollback ISP",fullName:"Rollback Owner",email:"rollback@nexus.test",password:"Strong-Test-Password-123"});
 assert.equal(failedSetup.status,500);
 assert.equal(db.prepare("SELECT COUNT(*) n FROM tenants").get().n,0);
 assert.equal(db.prepare("SELECT COUNT(*) n FROM users").get().n,0);
 db.exec("DROP TRIGGER fail_setup_session");
 const setup=await request("/api/v1/setup","POST",{companyName:"Nexus Test ISP",fullName:"Test Owner",email:"owner@nexus.test",password:"Strong-Test-Password-123"});
 assert.equal(setup.status,201);
 const token=setup.data.token;
 assert.equal(db.prepare("SELECT COUNT(*) n FROM schema_migrations WHERE version='001_database_hardening'").get().n,1);
 db.prepare("INSERT INTO tenants(id,name,slug) VALUES(?,?,?)").run("other-tenant","Other ISP","other-isp");
 db.prepare("INSERT INTO customers(id,tenant_id,customer_code,full_name) VALUES(?,?,?,?)").run("other-customer","other-tenant","OTHER-1","Other Subscriber");
 assert.throws(() => db.prepare("INSERT INTO invoices(id,tenant_id,customer_id,invoice_number,amount_pkr) VALUES(?,?,?,?,?)").run("cross-tenant-invoice",setup.data.user.tenantId,"other-customer","CROSS-1",100), /invoice customer tenant mismatch/);
 const customer=await request("/api/v1/customers","POST",{fullName:"Test Subscriber"},token);
 assert.equal(customer.status,201);
 const pack=await request("/api/v1/packages","POST",{name:"Test 10M",speedDownMbps:10,speedUpMbps:10,monthlyPricePkr:1500},token);
 assert.equal(pack.status,201);
 const sub=await request("/api/v1/subscriptions","POST",{customerId:customer.data.data.id,packageId:pack.data.data.id,status:"active"},token);
 assert.equal(sub.status,201);
 assert.match(customer.data.data.account_number,/^NXS-[0-9]{7}$/);
 assert.equal(customer.data.data.connection_status,"pending");
 assert.equal(db.prepare("SELECT COUNT(*) n FROM schema_migrations WHERE version='002_customer_subscription_management'").get().n,1);
 const installDate=new Date().toISOString().slice(0,10);
 const customerUpdate=await request("/api/v1/customers/"+customer.data.data.id,"PATCH",{serviceAddress:"Unit 8, Latifabad",coverageArea:"Latifabad Unit 8",installationDate:installDate,connectionStatus:"active"},token);
 assert.equal(customerUpdate.status,200);
 assert.equal(customerUpdate.data.data.service_address,"Unit 8, Latifabad");
 const filtered=await request("/api/v1/customers?q=Latifabad&page=1&pageSize=1","GET",undefined,token);
 assert.equal(filtered.status,200);
 assert.equal(filtered.data.pagination.total,1);
 assert.equal(filtered.data.data[0].id,customer.data.data.id);
 const expiry=new Date(Date.now()+30*86400000).toISOString().slice(0,10);
 const suspended=await request("/api/v1/subscriptions/"+sub.data.data.id,"PATCH",{status:"suspended",expiresAt:expiry},token);
 assert.equal(suspended.status,200);
 assert.equal(suspended.data.data.expires_at,expiry);
 const renewed=await request("/api/v1/subscriptions/"+sub.data.data.id+"/renew","POST",{days:30},token);
 assert.equal(renewed.status,200);
 assert.equal(renewed.data.data.status,"active");
 assert.ok(renewed.data.data.expires_at>expiry);
 const profile=await request("/api/v1/customers/"+customer.data.data.id+"/profile","GET",undefined,token);
 assert.equal(profile.status,200);
 assert.equal(profile.data.data.subscriptions.length,1);
 assert.ok(profile.data.data.connectionHistory.length>=2);
 assert.ok(profile.data.data.subscriptionHistory.some(x=>x.event_type==="renewed"));
 const router=await request("/api/v1/routers","POST",{name:"Core Router",host:"192.0.2.1",apiPort:8729,username:"router-test",password:"Router-Test-Secret-123"},token);
 assert.equal(router.status,201);
 const billingAttempts=await Promise.all([request("/api/v1/billing/generate","POST",{period:"2026-11"},token),request("/api/v1/billing/generate","POST",{period:"2026-11"},token)]);
 assert.equal(billingAttempts.filter(x=>x.status===201).length,1);
 assert.equal(billingAttempts.filter(x=>x.status===409).length,1);
 const billing=billingAttempts.find(x=>x.status===201);
 assert.equal(billing.data.invoicesCreated,1);
 const invoice=(await request("/api/v1/invoices","GET",undefined,token)).data.data[0];
 assert.ok(invoice);
 db.exec("CREATE TRIGGER fail_invoice_status BEFORE UPDATE OF status ON invoices BEGIN SELECT RAISE(ABORT, 'injected invoice status failure'); END");
 const failedPayment=await request("/api/v1/payments","POST",{invoiceId:invoice.id,amountPkr:100,method:"cash"},token);
 assert.equal(failedPayment.status,500);
 assert.equal(db.prepare("SELECT COUNT(*) n FROM payments WHERE invoice_id=?").get(invoice.id).n,0);
 assert.equal(db.prepare("SELECT status FROM invoices WHERE id=?").get(invoice.id).status,"unpaid");
 db.exec("DROP TRIGGER fail_invoice_status");
 const payment=await request("/api/v1/payments","POST",{invoiceId:invoice.id,amountPkr:100,method:"cash"},token);
 assert.equal(payment.status,201);
 assert.equal(db.prepare("SELECT status FROM invoices WHERE id=?").get(invoice.id).status,"partial");
 assert.throws(() => db.prepare("INSERT INTO payments(id,tenant_id,invoice_id,amount_pkr,method) VALUES(?,?,?,?,?)").run("overpay-test",setup.data.user.tenantId,invoice.id,2000,"cash"), /payment exceeds invoice total/);
 const staff=await request("/api/v1/staff","POST",{fullName:"Billing Staff",email:"billing@nexus.test",password:"Billing-Password-123",role:"billing"},token);
 assert.equal(staff.status,201);
 const staffLogin=await request("/api/v1/auth/login","POST",{email:"billing@nexus.test",password:"Billing-Password-123"});
 assert.equal(staffLogin.status,200);
 const billingToken=staffLogin.data.token;
 assert.equal((await request("/api/v1/staff","GET",undefined,billingToken)).status,403);
 assert.equal((await request("/api/v1/customers","POST",{fullName:"Denied Subscriber"},billingToken)).status,403);
 const permissionState=await request("/api/v1/staff/"+staff.data.data.id+"/permissions","GET",undefined,token);
 assert.equal(permissionState.status,200);
 assert.equal(permissionState.data.data.permissions.find(x=>x.key==="customers.create").allowed,false);
 const granted=await request("/api/v1/staff/"+staff.data.data.id+"/permissions","PUT",{allowedPermissions:["dashboard.read","customers.read","customers.create","packages.read","subscriptions.read","billing.read","invoices.create","payments.create","billing.generate","reports.read"]},token);
 assert.equal(granted.status,200);
 const allowedCustomer=await request("/api/v1/customers","POST",{fullName:"Permission Test Subscriber"},billingToken);
 assert.equal(allowedCustomer.status,201);
 const revoked=await request("/api/v1/staff/"+staff.data.data.id+"/permissions","PUT",{allowedPermissions:["dashboard.read","customers.read","packages.read","subscriptions.read","billing.read","invoices.create","payments.create","billing.generate","reports.read"]},token);
 assert.equal(revoked.status,200);
 assert.equal((await request("/api/v1/customers","POST",{fullName:"Revoked Subscriber"},billingToken)).status,403);
 assert.equal((await request("/api/v1/routers","GET",undefined,billingToken)).status,403);
 const technician=await request("/api/v1/staff","POST",{fullName:"Field Technician",email:"tech@nexus.test",password:"Technician-Password-123",role:"technician"},token);
 assert.equal(technician.status,201);
 const techLogin=await request("/api/v1/auth/login","POST",{email:"tech@nexus.test",password:"Technician-Password-123"});
 assert.equal(techLogin.status,200);
 assert.equal((await request("/api/v1/routers","GET",undefined,techLogin.data.token)).status,200);
 assert.equal((await request("/api/v1/routers","POST",{name:"Blocked Router",host:"192.0.2.2"},techLogin.data.token)).status,403);
 const reports=await request("/api/v1/reports/summary","GET",undefined,token);
 assert.equal(reports.status,200);
 console.log("Nexus smoke tests passed: core CRUD, atomic setup/payment rollback, concurrent monthly billing, role permissions, staff controls and router access.");
}finally{
 await new Promise(resolve=>server.close(resolve));
 rmSync(dir,{recursive:true,force:true});
}
